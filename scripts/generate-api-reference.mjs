#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const inputPath = path.resolve(repoRoot, process.argv[2] ?? 'api-reference/openapi.json');
const outputPath = path.resolve(repoRoot, process.argv[3] ?? 'api-reference.md');

const METHOD_ORDER = ['get', 'post', 'put', 'patch', 'delete', 'options', 'head'];

function text(value) {
  return String(value ?? '')
    .replace(/\s+\u2014\s+/g, ' - ')
    .replace(/\u2014/g, '-')
    .trim();
}

function schemaLabel(schema) {
  if (!schema) return 'object';
  if (schema.$ref) return schema.$ref;
  if (schema.type) return schema.type;
  if (schema.oneOf) return 'oneOf';
  if (schema.anyOf) return 'anyOf';
  if (schema.allOf) return 'allOf';
  return 'object';
}

function resolveRef(spec, ref) {
  if (!ref?.startsWith('#/')) return undefined;
  return ref
    .slice(2)
    .split('/')
    .reduce((current, part) => current?.[part], spec);
}

function responseDescription(spec, response) {
  if (!response) return '';
  if (response.$ref) {
    const resolved = resolveRef(spec, response.$ref);
    return text(resolved?.description || response.$ref.split('/').at(-1));
  }
  return text(response.description);
}

function renderParameters(parameters = []) {
  if (!parameters.length) return [];

  const lines = ['', '**Parameters:**'];
  for (const param of parameters) {
    const required = param.required ? 'required' : 'optional';
    const type = schemaLabel(param.schema);
    const description = text(param.description);
    const suffix = description ? `: ${description}` : '';
    lines.push(`- \`${param.name}\` (${param.in}, ${type}, ${required})${suffix}`);
  }
  return lines;
}

function renderRequestBody(requestBody) {
  if (!requestBody?.content) return [];

  const lines = ['', '**Request body:**'];
  for (const [contentType, body] of Object.entries(requestBody.content)) {
    lines.push(`${contentType} - ${schemaLabel(body.schema)}`);
  }
  return lines;
}

function renderResponses(spec, responses = {}) {
  const lines = ['', '**Responses:**'];
  for (const [status, response] of Object.entries(responses)) {
    const description = responseDescription(spec, response);
    const suffix = description ? ` - ${description}` : '';
    lines.push(`- \`${status}\`${suffix}`);
  }
  return lines;
}

function renderOperation(spec, route, method, operation) {
  const methodLabel = method.toUpperCase();
  const lines = [
    `### \`${methodLabel} ${route}\``,
    '',
    text(operation.summary || `${methodLabel} ${route}`),
  ];

  const description = text(operation.description);
  if (description) {
    lines.push('', description);
  }

  lines.push(...renderParameters(operation.parameters));
  lines.push(...renderRequestBody(operation.requestBody));
  lines.push(...renderResponses(spec, operation.responses));

  return lines.join('\n');
}

function render(spec) {
  const baseUrl = spec.servers?.[0]?.url;
  const generatedAt = new Date().toISOString();
  const lines = [
    '{/*',
    'This file is auto-generated by sigil-documentation-sync using scripts/generate-api-reference.mjs from api-reference/openapi.json.',
    'Do not edit by hand; changes will be overwritten on the next generated update.',
    'Edit the OpenAPI spec to update endpoint descriptions.',
    `Last generated: ${generatedAt}`,
    '*/}',
    '',
    '# API Reference',
    '',
    text(spec.info?.title || 'API Reference'),
    '',
    text(spec.info?.description || ''),
    '',
    `**Version:** ${text(spec.info?.version || 'unknown')}`,
  ];

  if (baseUrl) {
    lines.push(`**Base URL:** ${text(baseUrl)}`);
  }

  lines.push('', '## Endpoints', '');

  for (const [route, pathItem] of Object.entries(spec.paths || {})) {
    for (const method of METHOD_ORDER) {
      const operation = pathItem[method];
      if (!operation) continue;
      lines.push(renderOperation(spec, route, method, operation), '');
    }
  }

  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`;
}

const spec = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
fs.writeFileSync(outputPath, render(spec));
console.log(`Generated ${path.relative(repoRoot, outputPath)} from ${path.relative(repoRoot, inputPath)}`);
